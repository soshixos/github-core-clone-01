const TYPE_CODE: Record<GitObjectType, number> = { commit: 1, tree: 2, blob: 3, tag: 4 };
const CODE_TYPE: Record<number, GitObjectType> = { 1: 'commit', 2: 'tree', 3: 'blob', 4: 'tag' };

function writePackObjectHeader(type: GitObjectType, size: number): Buffer {
  const code = TYPE_CODE[type];
  const bytes: number[] = [];
  let remaining = size;
  let first = (code << 4) | (remaining & 0x0f);
  remaining = Math.floor(remaining / 16);
  while (remaining > 0) {
    bytes.push(first | 0x80);
    first = remaining & 0x7f;
    remaining = Math.floor(remaining / 128);
  }
  bytes.push(first);
  return Buffer.from(bytes);
}

/** Build a packfile from plain objects (no deltas). The trailer is SHA-1 over everything before it. */
export function writePack(objects: readonly GitObject[]): Buffer {
  const parts: Buffer[] = [];
  const header = Buffer.allocUnsafe(12);
  header.write('PACK', 0, 4, 'ascii');
  header.writeUInt32BE(2, 4);
  header.writeUInt32BE(objects.length, 8);
  parts.push(header);
  for (const object of objects) {
    parts.push(writePackObjectHeader(object.type, object.data.length));
    parts.push(deflateSync(object.data));
  }
  const body = Buffer.concat(parts);
  return Buffer.concat([body, createHash('sha1').update(body).digest()]);
}

/** True when the pack's trailer matches its bytes. */
export function verifyPackChecksum(pack: Uint8Array): boolean {
  const buffer = Buffer.isBuffer(pack) ? pack : Buffer.from(pack);
  if (buffer.length < 32) return false;
  const actual = buffer.subarray(buffer.length - 20).toString('hex');
  const expected = createHash('sha1').update(buffer.subarray(0, buffer.length - 20)).digest('hex');
  return actual === expected;
}

function readVarintSize(buffer: Buffer, start: number): { size: number; next: number; first: number } {
  let byte = buffer[start] as number;
  let size = byte & 0x0f;
  let shift = 4;
  let offset = start + 1;
  while ((byte & 0x80) !== 0) {
    byte = buffer[offset] as number;
    offset += 1;
    size |= (byte & 0x7f) << shift;
    shift += 7;
  }
  return { size, next: offset, first: buffer[start] as number };
}

/**
 * Inflate one zlib stream starting at `offset` and report the offset just past it.
 *
 * Node's `inflateSync` with `{ info: true }` returns the engine, whose `bytesWritten` is the
 * number of input bytes the stream consumed — exactly the stream's length, trailing bytes
 * excluded. One inflate per object, no searching.
 */
export function inflateAtSync(buffer: Buffer, offset: number, size: number): { data: Buffer; next: number } {
  let result: { buffer: Buffer; engine: { bytesWritten: number } };
  try {
    result = inflateSync(buffer.subarray(offset), { info: true }) as unknown as { buffer: Buffer; engine: { bytesWritten: number } };
  } catch (error) {
    throw new Error(`zlib stream at offset ${offset} did not inflate: ${error instanceof Error ? error.message : String(error)}`);
  }
  const written = result.engine.bytesWritten;
  if (!written || written <= 0) throw new Error(`zlib stream at offset ${offset} consumed no bytes`);
  if (result.buffer.length !== size) {
    throw new Error(`pack entry at offset ${offset} declares ${size} bytes but inflated to ${result.buffer.length}`);
  }
  return { data: result.buffer, next: offset + written };
}

/** Parse a packfile into its objects (plain objects only; deltas are rejected). */
export function readPack(pack: Uint8Array): Map<string, GitObject> {
  const buffer = Buffer.isBuffer(pack) ? pack : Buffer.from(pack);
  if (buffer.length < 32) throw new Error('pack is too short');
  if (buffer.toString('ascii', 0, 4) !== 'PACK') throw new Error('pack has no PACK header');
  const version = buffer.readUInt32BE(4);
  if (version !== 2 && version !== 3) throw new Error(`pack version ${version}`);
  const count = buffer.readUInt32BE(8);
  if (!verifyPackChecksum(buffer)) throw new Error('pack trailer checksum mismatch');
  const objects = new Map<string, GitObject>();
  let offset = 12;
  const end = buffer.length - 20;
  for (let i = 0; i < count; i += 1) {
    if (offset >= end) throw new Error('pack ends before its declared object count');
    const { size, next, first } = readVarintSize(buffer, offset);
    const typeCode = (first >> 4) & 0x07;
    if (typeCode === 6 || typeCode === 7) throw new Error('delta-compressed pack object (unsupported)');
    const type = CODE_TYPE[typeCode];
    if (type === undefined) throw new Error(`unknown pack object type ${typeCode}`);
    offset = next;
    const { data, next: after } = inflateAtSync(buffer, offset, size);
    if (data.length !== size) throw new Error(`pack object size mismatch: header ${size}, inflated ${data.length}`);
    objects.set(hashObject(type, data), { type, data });
    offset = after;
  }
  if (offset !== end) throw new Error('pack has trailing bytes before its trailer');
  return objects;
}
